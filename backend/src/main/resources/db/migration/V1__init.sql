-- 서비스 테이블 12개. enum은 varchar + CHECK, 시각은 timestamptz(UTC).
-- 공개 시 필수 항목은 NOT NULL이 아니라 PublishRules(서비스)가 검사한다.

CREATE TABLE users (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider           varchar(20)  NOT NULL,
    provider_id        varchar(255) NOT NULL,
    email              varchar(255),
    nickname           varchar(20)  NOT NULL,
    profile_image_url  varchar(500),
    role               varchar(10)  NOT NULL DEFAULT 'user',
    following_seen_at  timestamptz,
    created_at         timestamptz  NOT NULL,
    updated_at         timestamptz  NOT NULL,
    CONSTRAINT uq_users_provider UNIQUE (provider, provider_id),
    CONSTRAINT ck_users_role CHECK (role IN ('user', 'admin'))
);

CREATE TABLE makers (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            varchar(80),
    name            varchar(100) NOT NULL,
    kind            varchar(10)  NOT NULL,
    region          varchar(50),
    intro           varchar(200),
    website         varchar(500),
    instagram       varchar(200),
    affiliation_id  bigint,
    created_at      timestamptz  NOT NULL,
    updated_at      timestamptz  NOT NULL,
    CONSTRAINT uq_makers_slug UNIQUE (slug),
    CONSTRAINT ck_makers_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_makers_kind CHECK (kind IN ('person', 'studio', 'owner')),
    CONSTRAINT fk_makers_affiliation FOREIGN KEY (affiliation_id) REFERENCES makers (id)
);

CREATE TABLE places (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                   varchar(80),
    name                   varchar(100) NOT NULL,
    kind                   varchar(20),
    region                 varchar(50),
    address                varchar(200),
    lat                    numeric(9, 6),
    lng                    numeric(9, 6),
    access                 varchar(20),
    visit_note             varchar(100),
    summary                varchar(60),
    impression             varchar(400),
    sense_light            varchar(60),
    sense_sound            varchar(60),
    sense_scent            varchar(60),
    sense_touch            varchar(60),
    essay                  text,
    visited_by_editor_on   date,
    status                 varchar(10)  NOT NULL,
    suggested_by           bigint,
    suggestion_reason      varchar(300),
    suggestion_link        varchar(500),
    suggestion_maker_hint  varchar(100),
    published_at           timestamptz,
    created_at             timestamptz  NOT NULL,
    updated_at             timestamptz  NOT NULL,
    CONSTRAINT uq_places_slug UNIQUE (slug),
    CONSTRAINT ck_places_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_places_kind CHECK (kind IN ('cafe', 'bar', 'restaurant', 'stay', 'garden', 'museum',
                                              'gallery', 'bookstore', 'shop', 'religious', 'public', 'other')),
    CONSTRAINT ck_places_access CHECK (access IN ('walk_in', 'reservation', 'ticket', 'guests_only')),
    CONSTRAINT ck_places_status CHECK (status IN ('suggested', 'draft', 'published', 'paused', 'closed', 'rejected')),
    CONSTRAINT fk_places_suggested_by FOREIGN KEY (suggested_by) REFERENCES users (id) ON DELETE SET NULL
);

-- 둘러보기: published·paused를 published_at desc, id desc 커서로.
CREATE INDEX idx_places_status_published ON places (status, published_at DESC, id DESC);

CREATE TABLE place_credits (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    bigint       NOT NULL,
    maker_id    bigint       NOT NULL,
    role        varchar(20)  NOT NULL,
    verified    boolean      NOT NULL DEFAULT false,
    source_url  varchar(500),
    position    int          NOT NULL,
    CONSTRAINT ck_place_credits_role CHECK (role IN ('planning', 'branding', 'architecture', 'interior', 'landscape',
                                                     'lighting', 'furniture', 'scent', 'photography', 'owner', 'other')),
    CONSTRAINT fk_place_credits_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT fk_place_credits_maker FOREIGN KEY (maker_id) REFERENCES makers (id)
);

CREATE INDEX idx_place_credits_place ON place_credits (place_id);
CREATE INDEX idx_place_credits_maker ON place_credits (maker_id);

CREATE TABLE place_sources (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id  bigint       NOT NULL,
    title     varchar(200) NOT NULL,
    url       varchar(500) NOT NULL,
    type      varchar(20)  NOT NULL,
    position  int          NOT NULL,
    CONSTRAINT ck_place_sources_type CHECK (type IN ('article', 'video', 'instagram', 'official')),
    CONSTRAINT fk_place_sources_place FOREIGN KEY (place_id) REFERENCES places (id)
);

CREATE INDEX idx_place_sources_place ON place_sources (place_id);

CREATE TABLE place_photos (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    bigint       NOT NULL,
    object_key  varchar(200) NOT NULL,
    width       int          NOT NULL,
    height      int          NOT NULL,
    alt         varchar(200),
    credit      varchar(100),
    license     varchar(10)  NOT NULL,
    source_url  varchar(500),
    position    int          NOT NULL,
    CONSTRAINT uq_place_photos_object_key UNIQUE (object_key),
    CONSTRAINT ck_place_photos_license CHECK (license IN ('own', 'press', 'credited')),
    CONSTRAINT fk_place_photos_place FOREIGN KEY (place_id) REFERENCES places (id)
);

-- 대표 사진(position 0) 조회.
CREATE INDEX idx_place_photos_place ON place_photos (place_id, position);

CREATE TABLE place_embeds (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id  bigint       NOT NULL,
    type      varchar(20)  NOT NULL,
    url       varchar(500) NOT NULL,
    position  int          NOT NULL,
    CONSTRAINT ck_place_embeds_type CHECK (type IN ('youtube', 'instagram')),
    CONSTRAINT fk_place_embeds_place FOREIGN KEY (place_id) REFERENCES places (id)
);

CREATE INDEX idx_place_embeds_place ON place_embeds (place_id);

CREATE TABLE daily_picks (
    pick_date   date        PRIMARY KEY,
    place_id    bigint      NOT NULL,
    line        varchar(40) NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    CONSTRAINT uq_daily_picks_place UNIQUE (place_id),
    CONSTRAINT ck_daily_picks_weekday CHECK (extract(isodow FROM pick_date) BETWEEN 1 AND 5),
    CONSTRAINT fk_daily_picks_place FOREIGN KEY (place_id) REFERENCES places (id)
);

CREATE TABLE saves (
    user_id     bigint      NOT NULL,
    place_id    bigint      NOT NULL,
    status      varchar(10) NOT NULL,
    updated_at  timestamptz NOT NULL,
    CONSTRAINT pk_saves PRIMARY KEY (user_id, place_id),
    CONSTRAINT ck_saves_status CHECK (status IN ('want', 'been')),
    CONSTRAINT fk_saves_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_saves_place FOREIGN KEY (place_id) REFERENCES places (id)
);

-- 내 공간 탭: 상태별 최근 저장순.
CREATE INDEX idx_saves_user_status_updated ON saves (user_id, status, updated_at DESC);

CREATE TABLE follows (
    user_id     bigint      NOT NULL,
    maker_id    bigint      NOT NULL,
    created_at  timestamptz NOT NULL,
    CONSTRAINT pk_follows PRIMARY KEY (user_id, maker_id),
    CONSTRAINT fk_follows_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_follows_maker FOREIGN KEY (maker_id) REFERENCES makers (id)
);

CREATE INDEX idx_follows_maker ON follows (maker_id);

CREATE TABLE credit_suggestions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint,
    place_id     bigint       NOT NULL,
    role         varchar(20)  NOT NULL,
    maker_name   varchar(100) NOT NULL,
    source_url   varchar(500),
    is_self      boolean      NOT NULL DEFAULT false,
    status       varchar(10)  NOT NULL,
    created_at   timestamptz  NOT NULL,
    reviewed_at  timestamptz,
    CONSTRAINT ck_credit_suggestions_role CHECK (role IN ('planning', 'branding', 'architecture', 'interior', 'landscape',
                                                          'lighting', 'furniture', 'scent', 'photography', 'owner', 'other')),
    CONSTRAINT ck_credit_suggestions_status CHECK (status IN ('pending', 'accepted', 'declined')),
    CONSTRAINT fk_credit_suggestions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_credit_suggestions_place FOREIGN KEY (place_id) REFERENCES places (id)
);

CREATE TABLE llm_calls (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose        varchar(30)    NOT NULL,
    place_id       bigint,
    model          varchar(100)   NOT NULL,
    input_tokens   int            NOT NULL,
    output_tokens  int            NOT NULL,
    cost_usd       numeric(10, 6) NOT NULL,
    latency_ms     int            NOT NULL,
    retries        int            NOT NULL DEFAULT 0,
    success        boolean        NOT NULL,
    created_at     timestamptz    NOT NULL,
    CONSTRAINT fk_llm_calls_place FOREIGN KEY (place_id) REFERENCES places (id)
);

-- 관리자 AI 기록: 기간 요약.
CREATE INDEX idx_llm_calls_created ON llm_calls (created_at);
